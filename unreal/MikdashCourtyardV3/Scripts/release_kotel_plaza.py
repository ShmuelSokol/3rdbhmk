def _flag(command_line, table, what):
    tokens = [t.strip('"').lower() for t in command_line.split()]
    found = sorted({value for token in tokens for key, value in table.items()
                    if token == key or token.startswith(key + '=')})
    if len(found) > 1:
        raise RuntimeError('More than one %s flag: %s' % (what, found))
    return found[0] if found else None


def _main():
    try:
        import unreal                                                        # noqa: F401
        native = True
    except ImportError:
        native = False

    if not native:
        action = map_targets.revert_from_command_line()
        if action:
            print(json.dumps(map_targets.restore_checkpoint(action['receipt'],
                                                            dry_run=action['dryRun']), indent=2))
            return
        planned = offline_plan()
        print(json.dumps(planned, indent=2, default=str))
        if not planned['offlineOk']:
            raise SystemExit('Offline plan has failures: %r' % planned['failures'])
        return

    import unreal as ue
    command_line = ue.SystemLibrary.get_command_line()
    mode = _flag(command_line, MODE_FLAGS, 'mode')
    if not mode:
        raise RuntimeError('Choose exactly one mode: %s' % sorted(set(MODE_FLAGS.values())))
    target_key = map_targets.target_from_command_line(command_line=command_line)
    revert_receipt = None
    if mode == 'revert':
        import re
        match = re.search(r'-PlazaRevert=(?:"([^"]+)"|(\S+))', command_line, re.IGNORECASE)
        if not match:
            raise RuntimeError('-PlazaRevert needs =<apply receipt path>')
        revert_receipt = match.group(1) or match.group(2)
    rebuild = '-plazarebuild' in command_line.lower()
    try:
        receipt = run(target_key, mode, revert_receipt, rebuild)
        acceptance = receipt.get('acceptance') or {}
        clearance = ((acceptance.get('modernSurface') or {}).get('clearance') or {})
        ue.log('release_kotel_plaza[%s/%s]: %s; instances %s/%s; coverage %s%%; '
               'min clearance %s cm; errors %d'
               % (receipt['target'], mode, receipt['status'],
                  (receipt.get('readback') or {}).get('instancesPlaced'),
                  (receipt.get('readback') or {}).get('instancesPlanned'),
                  (acceptance.get('coverage') or {}).get('stationCoverageOfPolygonPercent'),
                  clearance.get('minCm'), len(receipt['errors'])))
    except Exception as error:                                               # noqa: BLE001
        ue.log_error('release_kotel_plaza failed: ' + repr(error))
        raise


if __name__ == '__main__':
    _main()
