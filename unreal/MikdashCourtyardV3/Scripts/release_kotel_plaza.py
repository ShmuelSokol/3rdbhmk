def run(target_key, mode, revert_receipt=None, rebuild=False):
    import unreal as ue
    if Path(ue.Paths.project_dir()).resolve() != ROOT:
        raise RuntimeError('Wrong project directory: ' + ue.Paths.project_dir())

    offline = offline_plan()
    if not offline['offlineOk']:
        raise RuntimeError('Offline plan has failures: %r' % offline['failures'])
    plan = json.loads(PLAN_PATH.read_text(encoding='utf-8-sig'))
    components = offline['components']

    stamp = stamp_now()
    native = Native(ue, target_key, mode, stamp)
    config = native.config
    target_map = config['map']
    map_file = ROOT / ('Content' + target_map[len('/Game'):] + '.umap')
    if not map_file.is_file():
        raise RuntimeError('Target map file missing: ' + str(map_file))

    if native.editor.get_game_world():
        raise RuntimeError('A game world is active; never mutate during play')
    if ue.EditorLoadingAndSavingUtils.get_dirty_map_packages() or \
       ue.EditorLoadingAndSavingUtils.get_dirty_content_packages():
        raise RuntimeError('Dirty packages present; resolve before checkpointed work')

    map_sha_before = sha256_of(map_file)
    protected_maps = {m: sha256_of(disk_path(m, 'umap')) for m in cut.PROTECTED_MAPS
                      if m != target_map and disk_path(m, 'umap').exists()}
    protected_assets = {TERRAIN_TWIN: sha256_of(disk_path(TERRAIN_TWIN))}
    for spec in components:
        protected_assets[spec['mesh']] = sha256_of(disk_path(spec['mesh']))
        protected_assets[spec['material']] = sha256_of(disk_path(spec['material']))
    protected_assets[KOTEL_MESH] = (sha256_of(disk_path(KOTEL_MESH))
                                    if disk_path(KOTEL_MESH).is_file() else None)

    native.receipt_path = FOLDER / ('native-kotel-plaza-%s-%s-%s.json'
                                    % (mode, config['key'], stamp))
    if native.receipt_path.exists():
        raise RuntimeError('Receipt already exists: ' + str(native.receipt_path))

    checkpoint = None
    if mode in ('apply', 'revert'):
        checkpoint = CHECKPOINT_ROOT / ('KotelPlaza-%s-%s' % (config['key'], stamp))
        checkpoint.mkdir(parents=True, exist_ok=False)
        shutil.copy2(map_file, checkpoint / map_file.name)
        if sha256_of(checkpoint / map_file.name) != map_sha_before:
            raise RuntimeError('Checkpoint copy hash differs from the live map')
        for folder_name in ('__ExternalActors__', '__ExternalObjects__'):
            external = ROOT / 'Content' / folder_name / target_map[6:]
            if external.exists():
                shutil.copytree(external, checkpoint / folder_name / target_map[6:])

    scale, translation = map_targets.placement_of(target_key)
    native.receipt = {
        'status': 'started_' + mode,
        'script': SCRIPT_TOKEN,
        'mode': mode, 'target': config['key'], 'stamp': stamp,
        'map': target_map, 'mapFile': str(map_file), 'mapSha256Before': map_sha_before,
        'checkpoint': str(checkpoint) if checkpoint else None,
        'protectedMapSha256Before': protected_maps,
        'protectedAssetSha256Before': protected_assets,
        'scriptSha256': offline['scriptSha256'],
        'engineVersion': ue.SystemLibrary.get_engine_version(),
        'userInstruction': ('"i also want you to restore the old city to its current modern '
                            'day layout... with kotel plaza and then houses up to that point" '
                            '- 9 September 2026. The houses half needed nothing; this is the '
                            'plaza half.'),
        'plan': offline,
        'placement': {
            'appliedTransform': 'identity',
            'declaredArchitecturePlacementForThisTarget': {
                'uniformScale': scale, 'translationCm': translation,
                'derivation': config['derivation']},
            'why': ('The plaza stands on the GROUND, not on the architecture. The 0.96 / '
                    '(-248, 0, 0) similarity was applied to the 2,633 architecture actors '
                    'only; the metric city and the 256 DEM ground tiles were never rescaled. '
                    'The decisive evidence is the terrain cut itself: kotel_job() in '
                    'release_precinct_terrain_cut.py takes no target argument, both maps cut '
                    'the same tile over the same 146 rectangles, and both read back the same '
                    '5,533 stations and the same 5.859375278305379e-06 cm. A plaza placed at '
                    '0.96 scale would not sit on the hole that was cut for it. Recorded as a '
                    'MEASUREMENT below in groundFrame and architectureFrame, not as a claim.'),
            'groundFrame': None, 'groundProof': None, 'architectureFrame': None},
        'stateContract': {
            'actorTags': [IDENTITY_TAG, STATE_TAG],
            'stateTag': STATE_TAG,
            'behaviour': ('%s is already in AMikdashEnclosure::HideWhileWallStandsTags '
                          '(MikdashEnclosure.cpp:204), so the actor is hidden while the '
                          'Yechezkel precinct stands and shown in MODERN and OVERLAY. No '
                          'plugin change and no rebuild is needed.' % STATE_TAG),
            'sharedWithTheTerrainTwin': ('Deliberate. The deck and the cut ground it stands '
                                         'in must appear and disappear together; one tag '
                                         'makes it impossible for them to disagree.'),
            'onDisk': 'hidden, collision off - the YECHEZKEL-correct state, as the twin was left.',
            'cannotBeCaughtByTheBuildingHidePath': (
                'BuildingIdentityLabel returns an empty label for a HISM-only actor and '
                'GatherModernBuildings skips empty labels, so no value in ExplicitHideLabels, '
                'ExplicitHideMeshNames or ModernBuildingLabelPrefixes can reach this actor.')},
        'reading': offline['reading'],
        'notBuilt': offline['notBuilt'],
        'limitations': offline['limitations'],
        'placed': [], 'readback': None, 'acceptance': None,
        'errors': [], 'mapSaved': False,
    }
    native.write_receipt()

    saved = False
    try:
        if not native.levels.load_level(target_map):
            raise RuntimeError('load_level failed for ' + target_map)
        world = native.editor.get_editor_world()
        if world.get_outermost().get_name() != target_map:
            raise RuntimeError('Loaded world is not the target map')

        rows = native.snapshot_rows()
        native.receipt['levelActorsWithAStaticMesh'] = len(rows)
        native.receipt['placement']['groundFrame'] = native.ground_frame(rows)
        native.receipt['placement']['groundProof'] = native.prove_ground(rows)
        by_key, _manifest = map_targets.architecture_index()
        native.receipt['placement']['architectureFrame'] = map_targets.prove_placement(
            rows, by_key, scale, translation)
        native.write_receipt()

        existing = native.plaza_actors()
        native.receipt['existingPlazaActorsBefore'] = [
            dict(name=a.get_name(), label=a.get_actor_label()) for a in existing]

        if mode == 'apply':
            if existing and not rebuild:
                raise RuntimeError('%d plaza actor(s) already in this map; pass -PlazaRebuild '
                                   'to replace, or -PlazaVerify to measure what is there'
                                   % len(existing))
            for actor in existing:
                native.actors.destroy_actor(actor)
            native.receipt['rebuiltOver'] = len(existing)
            _actor, placed = native.build(plan, components)
            native.receipt['placed'] = placed
            native.write_receipt()
            if not native.levels.save_current_level():
                raise RuntimeError('save_current_level returned False')
            saved = True
            native.receipt['mapSaved'] = True
            native.receipt['mapSha256AfterSave'] = sha256_of(map_file)
            native.write_receipt()
            if not native.levels.load_level(target_map):
                raise RuntimeError('Reopen failed')

        if mode == 'revert':
            prior = json.loads(Path(revert_receipt).read_text(encoding='utf-8-sig'))
            if prior.get('target') != config['key'] or prior.get('mode') != 'apply' \
                    or not prior.get('mapSaved'):
                raise RuntimeError('Revert needs a SAVED apply receipt for this target')
            label = prior['readback']['actorLabel'] if prior.get('readback') else ACTOR_LABEL
            destroyed = []
            for actor in native.plaza_actors():
                if actor.get_actor_label() == label:
                    destroyed.append(dict(name=actor.get_name(), label=label))
                    native.actors.destroy_actor(actor)
            if not destroyed:
                raise RuntimeError('Nothing to revert: no actor labelled ' + label)
            native.receipt['reverted'] = destroyed
            if not native.levels.save_current_level():
                raise RuntimeError('save_current_level returned False')
            saved = True
            native.receipt['mapSaved'] = True
            native.receipt['mapSha256AfterSave'] = sha256_of(map_file)
            if not native.levels.load_level(target_map):
                raise RuntimeError('Reopen failed')
            remaining = native.plaza_actors()
            native.receipt['plazaActorsAfterRevert'] = [a.get_actor_label() for a in remaining]
            if remaining:
                raise RuntimeError('Plaza actors survive the revert: %s'
                                   % native.receipt['plazaActorsAfterRevert'])
            native.receipt['status'] = 'kotel_plaza_reverted_saved_reopened'

        if mode in ('apply', 'verify'):
            readback, deck_cells = read_back(native, plan, components)
            native.receipt['readback'] = readback
            native.write_receipt()
            native.receipt['acceptance'] = measure(native, offline, deck_cells)
            headline = native.receipt['acceptance']['modernSurface']['clearance']
            if headline['stationsWithTerrainAboveDeckUnderside'] > 0:
                raise RuntimeError(
                    'The cut terrain still pierces the placed deck at %d of %d stations, worst '
                    '%.4f cm above the underside'
                    % (headline['stationsWithTerrainAboveDeckUnderside'], headline['stations'],
                       headline['maxTerrainHeightAboveDeckUndersideCm']))
            native.receipt['status'] = (
                'kotel_plaza_placed_saved_reopened_measured_visual_acceptance_pending'
                if mode == 'apply' else 'kotel_plaza_measured_map_unchanged')
    except Exception as error:                                               # noqa: BLE001
        native.receipt['errors'].append({'stage': mode, 'error': repr(error)})
        native.receipt['status'] = ('FAILED_AFTER_SAVE_CHECKPOINT_AVAILABLE' if saved
                                    else 'FAILED_BEFORE_SAVE_MAP_UNCHANGED')
        raise
    finally:
        native.receipt['mapSha256After'] = sha256_of(map_file)
        native.receipt['mapBytesChanged'] = \
            native.receipt['mapSha256After'] != map_sha_before
        native.receipt['protectedMapsUnchanged'] = all(
            sha256_of(disk_path(m, 'umap')) == value for m, value in protected_maps.items())
        native.receipt['protectedAssetsUnchanged'] = all(
            value is None or sha256_of(disk_path(p)) == value
            for p, value in protected_assets.items())
        if mode == 'verify' and native.receipt['mapBytesChanged']:
            native.receipt['errors'].append(
                {'stage': 'finally', 'error': '-PlazaVerify must not change the map, and it did.'})
        native.write_receipt()
    return native.receipt


