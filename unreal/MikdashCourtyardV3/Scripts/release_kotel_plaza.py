class Native(object):
    def __init__(self, ue, target_key, mode, stamp):
        self.ue = ue
        self.target_key = target_key
        self.config = map_targets.target_config(target_key)
        self.mode = mode
        self.stamp = stamp
        for name in ('GeometryScript_AssetUtils', 'GeometryScript_MeshQueries'):
            if not hasattr(ue, name):
                raise RuntimeError('Launch with -EnablePlugins=GeometryScripting: ' + name)
        self.query = ue.GeometryScript_MeshQueries
        self.asset_utils = ue.GeometryScript_AssetUtils
        self.editor = ue.get_editor_subsystem(ue.UnrealEditorSubsystem)
        self.assets = ue.get_editor_subsystem(ue.EditorAssetSubsystem)
        self.actors = ue.get_editor_subsystem(ue.EditorActorSubsystem)
        self.levels = ue.get_editor_subsystem(ue.LevelEditorSubsystem)
        self.receipt = {}
        self.receipt_path = None
        self.transform_path = None

    def write_receipt(self):
        self.receipt_path.parent.mkdir(parents=True, exist_ok=True)
        self.receipt_path.write_text(
            json.dumps(self.receipt, indent=2, sort_keys=False) + '\n', encoding='utf-8')

    # -- level census ------------------------------------------------------
    def mesh_of(self, actor):
        component = actor.get_component_by_class(self.ue.StaticMeshComponent)
        if component is None:
            return None, None
        return component, component.get_editor_property('static_mesh')

    def snapshot_rows(self):
        """One row per level actor: label, the mesh assets it renders, and its world AABB.

        The shape map_targets.prove_placement() and terrain_fingerprint() both expect.
        """
        ue = self.ue
        rows = []
        for actor in self.actors.get_all_level_actors():
            meshes = []
            for component in actor.get_components_by_class(ue.StaticMeshComponent):
                mesh = component.get_editor_property('static_mesh')
                if mesh is not None:
                    meshes.append(mesh.get_path_name())
            if not meshes:
                continue
            origin, extent = actor.get_actor_bounds(False)
            rows.append(dict(
                label=actor.get_actor_label(), name=actor.get_name(), meshes=meshes,
                bounds={'min': [origin.x - extent.x, origin.y - extent.y, origin.z - extent.z],
                        'max': [origin.x + extent.x, origin.y + extent.y, origin.z + extent.z]}))
        return rows

    def ground_frame(self, rows):
        """The two things the plaza is registered against, in world centimetres.

        Identical between the Candidate48 and Main50 receipts is the measurement that says
        the identity is the right transform for this pass.
        """
        wanted = {}
        for row in rows:
            names = [m.rsplit('/', 1)[-1].split('.')[0] for m in row['meshes']]
            if TERRAIN_TILE in names or (TERRAIN_TILE + '_FutureMountCut') in names:
                wanted.setdefault('terrainTileActor', []).append(
                    dict(label=row['label'], meshes=row['meshes'],
                         bounds={k: [round(v, 4) for v in row['bounds'][k]]
                                 for k in ('min', 'max')}))
            if KOTEL_MESH.rsplit('/', 1)[-1] in names:
                wanted.setdefault('kotelBuildingActor', []).append(
                    dict(label=row['label'], meshes=row['meshes'],
                         bounds={k: [round(v, 4) for v in row['bounds'][k]]
                                 for k in ('min', 'max')}))
        return wanted

    def prove_ground(self, rows):
        """The ground has not moved - which is the entire licence for identity placement.

        Every SM_JerusalemTerrain_* actor's live world AABB against the same tile read off the
        live Main50 level by Scripts/candidate_placement_proof.py. Not believed: measured.
        """
        live = {k: v for k, v in map_targets.terrain_fingerprint(rows).items()
                if not any(token in k for token in CUT_TWIN_TOKENS)}
        report = dict(target=self.config['key'], liveGroundTiles=len(live),
                      reference=str(GROUND_REFERENCE),
                      toleranceCm=GROUND_PARITY_TOLERANCE_CM,
                      cutTwinTokensExcluded=list(CUT_TWIN_TOKENS))
        if self.target_key == map_targets.AUTHORING_TARGET:
            report['status'] = 'authoring_frame_is_its_own_reference'
            return report
        if not GROUND_REFERENCE.is_file():
            raise RuntimeError(
                'No Main50 ground fingerprint at %s. Placing on %s at identity coordinates is '
                'only correct if the terrain is proved to be the same terrain.'
                % (GROUND_REFERENCE, self.config['key']))
        reference = json.loads(GROUND_REFERENCE.read_text(encoding='utf-8-sig'))
        comparison = map_targets.compare_fingerprints(reference['tiles'], live)
        report.update(comparison)
        report['referenceStamp'] = reference.get('stamp')
        if comparison['matchedLabels'] < 200:
            raise RuntimeError('Only %d ground tiles matched the Main50 fingerprint'
                               % comparison['matchedLabels'])
        if comparison['worstBoundsErrorCm'] > GROUND_PARITY_TOLERANCE_CM:
            raise RuntimeError('The ground is NOT the same terrain on %s: worst tile AABB '
                               'differs by %.4f cm on %s. Identity placement would be wrong.'
                               % (self.config['key'], comparison['worstBoundsErrorCm'],
                                  comparison['worstLabel']))
        report['status'] = 'ground_is_identical_to_main50_identity_placement_is_correct'
        return report

    # -- placement ---------------------------------------------------------
    def make_transform(self, row):
        ue = self.ue
        location = ue.Vector(float(row['loc'][0]), float(row['loc'][1]), float(row['loc'][2]))
        rotation = ue.Rotator(pitch=float(row['rot'][1]), yaw=float(row['rot'][2]),
                              roll=float(row['rot'][0]))
        scale = ue.Vector(float(row['scale'][0]), float(row['scale'][1]), float(row['scale'][2]))
        if self.transform_path is None:
            self.transform_path = self._probe_transform_path(location, rotation, scale)
        if self.transform_path == 'keyword_rotation_translation_scale':
            return ue.Transform(rotation=rotation, translation=location, scale=scale)
        transform = ue.Transform()
        transform.set_editor_property('translation', location)
        transform.set_editor_property('rotation', rotation.quaternion())
        transform.set_editor_property('scale3d', scale)
        return transform

    def _probe_transform_path(self, location, rotation, scale):
        """unreal.Transform's POSITIONAL order is (rotation, translation, scale). A run that
        assumes (translation, rotation, scale) places 1,029 instances at the origin and still
        passes an instance-count check, so the construction path is probed and recorded."""
        ue = self.ue
        try:
            probe = ue.Transform(rotation=rotation, translation=location, scale=scale)
            got = probe.get_editor_property('translation')
            if (abs(got.x - location.x) < 1e-3 and abs(got.y - location.y) < 1e-3
                    and abs(got.z - location.z) < 1e-3):
                self.receipt['transformConstruction'] = 'keyword_rotation_translation_scale'
                return 'keyword_rotation_translation_scale'
        except Exception as error:                                           # noqa: BLE001
            self.receipt.setdefault('limitations', []).append(
                'unreal.Transform keyword construction unavailable (%r)' % (error,))
        self.receipt['transformConstruction'] = 'set_editor_property'
        return 'set_editor_property'

    def new_hism(self, actor):
        """Instance-owned HISM on a plain editor actor, via the editor subobject path.

        UE 5.8 does not expose AActor::AddComponentByClass to Python (it raises
        AttributeError - the failure that cost release_city_detail.py its first run), and
        constructing the component with outer=actor makes one the level never owns.
        Ownership is verified three ways before an instance is added.
        """
        ue = self.ue
        subsystem = ue.get_engine_subsystem(ue.SubobjectDataSubsystem)
        library = ue.SubobjectDataBlueprintFunctionLibrary
        handles = subsystem.k2_gather_subobject_data_for_instance(actor)
        parent = next((h for h in handles
                       if library.get_associated_object(library.get_data(h)) == actor), None)
        if parent is None:
            raise RuntimeError('Editor actor subobject handle missing')
        params = ue.AddNewSubobjectParams(
            parent_handle=parent,
            new_class=ue.HierarchicalInstancedStaticMeshComponent,
            blueprint_context=None, conform_transform_to_parent=True)
        handle, reason = subsystem.add_new_subobject(params)
        if not library.is_handle_valid(handle):
            raise RuntimeError('Persistent HISM creation failed: ' + str(reason))
        data = library.get_data(handle)
        component = library.get_associated_object(data)
        if not isinstance(component, ue.HierarchicalInstancedStaticMeshComponent):
            raise RuntimeError('Subobject is a %s, not a HISM' % type(component).__name__)
        if component.get_owner() != actor or not library.is_instanced_component(data):
            raise RuntimeError('HISM ownership / instance creation not verified')
        if component not in actor.get_components_by_class(
                ue.HierarchicalInstancedStaticMeshComponent):
            raise RuntimeError('HISM absent from the actor component readback')
        return component

    def add_instances(self, component, transforms):
        try:
            component.add_instances(transforms, False, True, False)
            self.receipt.setdefault('instanceApi', 'add_instances(world_space=True)')
        except TypeError:
            component.add_instances(transforms, False)
            self.receipt.setdefault('instanceApi', 'add_instances(local, actor at identity)')

    def plaza_actors(self):
        return [a for a in self.actors.get_all_level_actors()
                if a.get_actor_label() == ACTOR_LABEL
                or IDENTITY_TAG in [str(t) for t in a.get_editor_property('tags')]]

    def build(self, plan, components):
        ue = self.ue
        actor = self.actors.spawn_actor_from_class(
            ue.Actor, ue.Vector(0.0, 0.0, 0.0), ue.Rotator(pitch=0.0, yaw=0.0, roll=0.0))
        if actor is None:
            raise RuntimeError('spawn_actor_from_class returned None')
        actor.set_actor_label(ACTOR_LABEL)
        actor.set_folder_path(ACTOR_FOLDER)
        actor.set_editor_property('tags', [ue.Name(IDENTITY_TAG), ue.Name(STATE_TAG)])
        placed = []
        try:
            for spec in components:
                rows = plan[spec['key']]
                mesh = ue.load_asset(spec['mesh'])
                if not isinstance(mesh, ue.StaticMesh):
                    raise RuntimeError('Missing mesh ' + spec['mesh'])
                material = ue.load_asset(spec['material'])
                if material is None:
                    raise RuntimeError('Missing material ' + spec['material'])
                component = self.new_hism(actor)
                component.set_editor_property('static_mesh', mesh)
                component.set_mobility(ue.ComponentMobility.STATIC)
                component.set_material(0, material)
                component.set_editor_property('cast_shadow', bool(spec['castShadow']))
                # Walkable in MODERN, and nothing else. Navigation is left off: a hidden
                # actor that feeds the navmesh would change the map's built nav data as a
                # side effect of this pass, which is not what was asked for.
                component.set_collision_profile_name('BlockAll')
                component.set_editor_property('can_ever_affect_navigation', False)
                transforms = [self.make_transform(row) for row in rows]
                self.add_instances(component, transforms)
                count = int(component.get_instance_count())
                if count != len(rows):
                    raise RuntimeError('%s: planned %d instances, the component reports %d'
                                       % (spec['key'], len(rows), count))
                placed.append(dict(key=spec['key'], component=component.get_name(),
                                   mesh=spec['mesh'], material=spec['material'],
                                   planned=len(rows), placed=count,
                                   castShadow=bool(spec['castShadow']),
                                   collisionProfile=str(
                                       component.get_collision_profile_name())))
                del transforms
        except Exception:
            self.actors.destroy_actor(actor)
            raise
        # The YECHEZKEL-correct state on disk, and exactly how the terrain twin under it was
        # left: hidden, collision off. ApplyStateTaggedActors turns both on together in
        # MODERN, in a game world.
        actor.set_actor_hidden_in_game(True)
        actor.set_actor_enable_collision(False)
        return actor, placed

    # -- terrain -----------------------------------------------------------
    def extract(self, mesh):
        """The SOURCE MODEL triangles of a static mesh, the way the cut that built the twin
        read them. Not a line trace: the twin actor's collision is deliberately off."""
        ue = self.ue
        dynamic = ue.DynamicMesh()
        options = ue.GeometryScriptCopyMeshFromAssetOptions()
        options.set_editor_property('apply_build_settings', False)
        options.set_editor_property('request_tangents', False)
        options.set_editor_property('use_build_scale', False)
        lod = ue.GeometryScriptMeshReadLOD()
        lod.set_editor_property('lod_type', ue.GeometryScriptLODType.SOURCE_MODEL)
        lod.set_editor_property('lod_index', 0)
        result = self.asset_utils.copy_mesh_from_static_mesh_v2(mesh, dynamic, options, lod)
        if ue.GeometryScriptOutcomePins.SUCCESS not in result:
            raise RuntimeError('Source-mesh extraction failed for ' + mesh.get_path_name())
        faces = []
        for tid in range(dynamic.get_triangle_count()):
            positions = [[v.x, v.y, v.z]
                         for v in self.query.get_triangle_positions(dynamic, tid)
                         if isinstance(v, ue.Vector)]
            if len(positions) != 3:
                raise RuntimeError('Incomplete triangle readback on ' + mesh.get_path_name())
            faces.append(positions)
        return faces

    def terrain_over_plaza(self, bbox):
        """Every terrain actor whose mesh bounds overlap the plaza footprint, with what it
        renders and whether it is visible in the state saved on disk."""
        ue = self.ue
        rows = []
        for actor in self.actors.get_all_level_actors():
            component, mesh = self.mesh_of(actor)
            if mesh is None or not mesh.get_name().startswith('SM_JerusalemTerrain_'):
                continue
            bounds = mesh.get_bounds()
            origin, extent = bounds.origin, bounds.box_extent
            if (origin.x + extent.x <= bbox[0] or origin.x - extent.x >= bbox[2]
                    or origin.y + extent.y <= bbox[1] or origin.y - extent.y >= bbox[3]):
                continue
            rows.append(dict(actor=actor.get_name(), label=actor.get_actor_label(),
                             mesh=mesh.get_name(),
                             meshPath=mesh.get_path_name().split('.')[0],
                             hiddenInGame=bool(actor.get_editor_property('hidden')),
                             collision=bool(actor.get_actor_enable_collision()),
                             tags=[str(t) for t in actor.get_editor_property('tags')]))
        return rows


def read_back(native, plan, components):
    """Every claim, off the REOPENED map: which actor, which components, how many instances
    each, and a numeric transform sample of each against the plan it was built from."""
    ue = native.ue
    matches = native.plaza_actors()
    if len(matches) != 1:
        raise RuntimeError('Expected exactly one %s actor after reopen, found %d'
                           % (ACTOR_LABEL, len(matches)))
    actor = matches[0]
    tags = [str(t) for t in actor.get_editor_property('tags')]
    hisms = list(actor.get_components_by_class(ue.HierarchicalInstancedStaticMeshComponent))
    by_mesh = {}
    for component in hisms:
        mesh = component.get_editor_property('static_mesh')
        by_mesh[mesh.get_path_name().split('.')[0] if mesh else None] = component

    rows = []
    deck_cells = None
    for spec in components:
        component = by_mesh.get(spec['mesh'])
        if component is None:
            raise RuntimeError('No component renders %s after reopen' % spec['mesh'])
        planned = plan[spec['key']]
        count = int(component.get_instance_count())
        material = component.get_material(0)
        worst = 0.0
        worst_scale = 0.0
        worst_yaw = 0.0
        cells = []
        for index in range(count):
            transform = component.get_instance_transform(index, True)
            location = transform.get_editor_property('translation')
            scale = transform.get_editor_property('scale3d')
            rotator = transform.get_editor_property('rotation').rotator()
            row = planned[index]
            worst = max(worst, abs(location.x - row['loc'][0]), abs(location.y - row['loc'][1]),
                        abs(location.z - row['loc'][2]))
            worst_scale = max(worst_scale, abs(scale.x - row['scale'][0]),
                              abs(scale.y - row['scale'][1]), abs(scale.z - row['scale'][2]))
            worst_yaw = max(worst_yaw,
                            abs(((float(rotator.yaw) - row['rot'][2]) + 180.0) % 360.0 - 180.0))
            if spec['key'] == 'deck':
                cells.append((location.x, location.y, location.z, scale.x, scale.y, scale.z))
        if count != len(planned):
            raise RuntimeError('%s: %d instances after reopen, the plan holds %d'
                               % (spec['key'], count, len(planned)))
        if worst > INSTANCE_TOLERANCE_CM or worst_scale > 1e-3 or worst_yaw > 0.05:
            raise RuntimeError('%s read back off the plan by %.4f cm / %.5f scale / %.4f deg'
                               % (spec['key'], worst, worst_scale, worst_yaw))
        if spec['key'] == 'deck':
            deck_cells = cells
        rows.append(dict(key=spec['key'], component=component.get_name(),
                         mesh=spec['mesh'],
                         meshAfterReopen=(component.get_editor_property('static_mesh')
                                          .get_path_name().split('.')[0]),
                         material=spec['material'],
                         materialAfterReopen=(material.get_path_name().split('.')[0]
                                              if material else None),
                         materialMatches=bool(material is not None
                                              and material.get_path_name().split('.')[0]
                                              == spec['material']),
                         planned=len(planned), placed=count,
                         allInstancesChecked=count,
                         worstLocationErrorCm=round(worst, 6),
                         worstScaleError=round(worst_scale, 8),
                         worstYawErrorDeg=round(worst_yaw, 6),
                         castShadow=bool(component.get_editor_property('cast_shadow')),
                         collisionProfile=str(component.get_collision_profile_name()),
                         affectsNavigation=bool(
                             component.get_editor_property('can_ever_affect_navigation'))))
    return dict(actor=actor.get_name(), actorLabel=actor.get_actor_label(),
                folderPath=str(actor.get_folder_path()),
                tags=tags,
                identityTagPresent=IDENTITY_TAG in tags,
                stateTagPresent=STATE_TAG in tags,
                hiddenInGameOnDisk=bool(actor.get_editor_property('hidden')),
                collisionOnDisk=bool(actor.get_actor_enable_collision()),
                componentCount=len(hisms), components=rows,
                instancesPlaced=sum(r['placed'] for r in rows),
                instancesPlanned=sum(r['planned'] for r in rows)), deck_cells


def measure(native, offline, deck_cells):
    """THE ACCEPTANCE. Coverage of the sourced polygon, and the clearance between the PLACED
    deck and the cut terrain under it - both computed from what is in the level, not from the
    plan file and not from the terrain cut's own receipt."""
    polygon = plaza_polygon()
    polygon_area_cm2 = abs(gen.polygon_area(polygon))
    thickness = float(offline['deckThicknessCm'])

    # Cells and undersides FROM THE PLACED INSTANCES.
    regions = []
    deck_area_cm2 = 0.0
    for x, y, z, sx, sy, sz in deck_cells:
        if abs(sz - 1.0) > 1e-6:
            raise RuntimeError('A placed deck cell is scaled in Z by %g' % sz)
        half_x, half_y = 625.0 * sx, 625.0 * sy
        regions.append(([x - half_x, y - half_y, x + half_x, y + half_y], z - thickness))
        deck_area_cm2 += (2 * half_x) * (2 * half_y)
    index = cut.RegionIndex(regions)
    bbox = [min(r[0][0] for r in regions), min(r[0][1] for r in regions),
            max(r[0][2] for r in regions), max(r[0][3] for r in regions)]

    # The terrain. The plaza is a MODERN feature, so the surface it must clear is the one
    # MODERN shows: the KotelPlazaCut twin. The YECHEZKEL-state surface is measured too, and
    # reported, because it is buried 11 m under the precinct deck and is expected to fail.
    terrain_rows = native.terrain_over_plaza(bbox)
    fields = {}
    for row in terrain_rows:
        mesh = native.ue.load_asset(row['meshPath'])
        if mesh is None:
            continue
        field = cut.HeightField()
        field.add(native.extract(mesh))
        fields[row['label']] = (row, field)
    twin_row = next((v for v in fields.values()
                     if v[0]['meshPath'] == TERRAIN_TWIN), None)
    if twin_row is None:
        raise RuntimeError('The KotelPlazaCut twin (%s) is not in the level over the plaza; '
                           'terrain actors found: %s'
                           % (TERRAIN_TWIN, [r['label'] for r in terrain_rows]))

    stations, nx, ny, dx, dy = cut.grid_stations(bbox, SAMPLE_SPACING_CM)
    in_polygon = on_deck = off_polygon_deck = 0
    per_surface = {}
    for label, (row, field) in fields.items():
        per_surface[label] = dict(
            mesh=row['mesh'], meshPath=row['meshPath'],
            hiddenInGameOnDisk=row['hiddenInGame'], tags=row['tags'],
            stations=0, missing=0, clearances=[])
    for x, y in stations:
        inside = gen.point_in_polygon((x, y), polygon)
        if inside:
            in_polygon += 1
        target = index.target(x, y)
        if target is None:
            continue
        on_deck += 1
        if not inside:
            off_polygon_deck += 1
        for label, (row, field) in fields.items():
            z = field.height(x, y)
            bucket = per_surface[label]
            if z is None:
                bucket['missing'] += 1
                continue
            bucket['stations'] += 1
            bucket['clearances'].append(target - z)

    def summarise(values):
        if not values:
            return None
        ordered = sorted(values)
        n = len(ordered)
        return dict(
            stations=n,
            minCm=round(ordered[0], 9),
            p05Cm=round(ordered[max(0, int(round(0.05 * (n - 1))))], 4),
            medianCm=round(ordered[(n - 1) // 2], 4),
            p95Cm=round(ordered[min(n - 1, int(round(0.95 * (n - 1))))], 4),
            maxCm=round(ordered[-1], 4),
            stationsWithTerrainAboveDeckUnderside=sum(1 for v in ordered if v < -TOLERANCE_CM),
            maxTerrainHeightAboveDeckUndersideCm=round(-ordered[0], 9))

    surfaces = {}
    for label, bucket in per_surface.items():
        surfaces[label] = dict(
            mesh=bucket['mesh'], meshPath=bucket['meshPath'],
            hiddenInGameOnDisk=bucket['hiddenInGameOnDisk'], tags=bucket['tags'],
            isTheModernSurface=(bucket['meshPath'] == TERRAIN_TWIN),
            stationsWithNoTerrain=bucket['missing'],
            clearance=summarise(bucket['clearances']))

    twin_label = twin_row[0]['label']
    headline = surfaces[twin_label]['clearance']
    return dict(
        method=('A %g cm grid over the placed deck bbox. A station counts as ON DECK when it '
                'falls inside a placed deck cell; clearance is that cell\'s underside minus '
                'the terrain height under it, so POSITIVE is deck above ground and NEGATIVE '
                'is terrain piercing the slab.' % SAMPLE_SPACING_CM),
        gridSpacingCm=SAMPLE_SPACING_CM, gridStationsX=nx, gridStationsY=ny,
        exactSpacingXCm=round(dx, 6), exactSpacingYCm=round(dy, 6),
        stationsSampled=len(stations),
        deckBboxCm=[round(v, 4) for v in bbox],
        coverage=dict(
            polygonOsmWay=offline['osmWay'],
            polygonVertices=len(polygon),
            polygonAreaM2=round(polygon_area_cm2 / 1e4, 3),
            deckAreaFromPlacedInstancesM2=round(deck_area_cm2 / 1e4, 3),
            deckAreaVersusPolygonPercent=round(100.0 * deck_area_cm2 / polygon_area_cm2, 3),
            stationsInsidePolygon=in_polygon,
            stationsOnDeck=on_deck,
            stationsOnDeckOutsidePolygon=off_polygon_deck,
            stationCoverageOfPolygonPercent=(round(100.0 * (on_deck - off_polygon_deck)
                                                   / in_polygon, 3) if in_polygon else None),
            note=('Two independent coverage numbers: the summed area of the 926 placed cells '
                  'against the sourced polygon, and the fraction of a %g cm grid of '
                  'in-polygon stations that lands on placed deck. They are computed by '
                  'different arithmetic and should agree.' % SAMPLE_SPACING_CM)),
        modernSurface=dict(
            actorLabel=twin_label, meshPath=TERRAIN_TWIN,
            why=('The plaza is a MODERN feature; the terrain MODERN shows under it is the '
                 'KotelPlazaCut twin. This is the clearance the acceptance is about.'),
            clearance=headline),
        allTerrainSurfacesOverThePlaza=surfaces,
        terrainActorsOverThePlaza=terrain_rows)


